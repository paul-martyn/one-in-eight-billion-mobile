#!/usr/bin/env node
// Генерирует src/design/tokens.css из src/design/tokens.json и src/design/motion.json.
// Имена переменных совпадают с tokens.uss Unity-порта (--color-…, --radius-…, --space-…,
// --font-size-…, --duration-…), чтобы вёрстка переносилась без переименований.
// tokens.css руками не правится: измените JSON и перезапустите скрипт.
//
// node tools/design/tokens-to-css.mjs          — записать файл
// node tools/design/tokens-to-css.mjs --check  — проверить, что файл совпадает с JSON
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const tokensPath = path.join(root, 'src', 'design', 'tokens.json');
const motionPath = path.join(root, 'src', 'design', 'motion.json');
export const outPath = path.join(root, 'src', 'design', 'tokens.css');

const kebab = s => String(s).replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

function outline({ axis, diag, drop, color }) {
  const layers = [[axis, 0], [-axis, 0], [0, axis], [0, -axis], [diag, diag], [-diag, diag], [diag, -diag], [-diag, -diag], [0, drop]];
  return layers.map(([x, y]) => `${x}px ${y}px 0 ${color}`).join(', ');
}

export function buildCss() {
  const t = JSON.parse(fs.readFileSync(tokensPath, 'utf8'));
  const m = JSON.parse(fs.readFileSync(motionPath, 'utf8'));
  const groups = [];
  const group = (title, entries) => { if (entries.length) groups.push(`  /* ${title} */\n${entries.map(([k, v]) => `  --${k}: ${v};`).join('\n')}`); };

  group('Цвета', Object.entries(t.color ?? {}).map(([k, v]) => [`color-${kebab(k)}`, v]));
  group('Показатели', Object.entries(t.stat ?? {}).map(([k, v]) => [`color-stat-${kebab(k)}`, v.color]));
  group('Разделы', Object.entries(t.section ?? {}).map(([k, v]) => [`color-section-${kebab(k)}`, v]));
  const journal = [];
  for (const [g, v] of Object.entries(t.journal ?? {})) {
    if (typeof v === 'string') journal.push([`color-journal-${kebab(g)}`, v]);
    else for (const [k, c] of Object.entries(v)) journal.push([`color-journal-${kebab(g)}-${kebab(k)}`, c]);
  }
  group('Дневник', journal);
  group('Шрифты', [['font-display', t.font.display], ['font-typed', t.font.typed], ['font-signature', t.font.signature]]);
  group('Кегль', Object.entries(t.type?.size ?? {}).map(([k, v]) => [`font-size-${kebab(k)}`, `${v}px`]));
  group('Межстрочный интервал', Object.entries(t.type?.lineHeight ?? {}).map(([k, v]) => [`line-height-${kebab(k)}`, String(v)]));
  group('Отступы', Object.entries(t.space ?? {}).map(([k, v]) => [`space-${kebab(k)}`, `${v}px`]));
  group('Радиусы', Object.entries(t.radius ?? {}).map(([k, v]) => [`radius-${kebab(k)}`, `${v}px`]));
  group('Тени', Object.entries(t.shadow ?? {}).map(([k, v]) => [`shadow-${kebab(k)}`, v]));
  group('Контур текста', Object.entries(t.outlineText ?? {}).map(([k, v]) => [`text-outline-${kebab(k)}`, outline(v)]));
  group('Длительности', Object.entries(m.duration ?? {}).filter(([, v]) => typeof v === 'number').map(([k, v]) => [`duration-${kebab(k)}`, `${v}ms`]));
  group('Кривые', Object.entries(m.easing ?? {}).filter(([, v]) => Array.isArray(v)).map(([k, v]) => [`ease-${kebab(k)}`, `cubic-bezier(${v.join(', ')})`]));
  group('Кадр', [['frame-width', `${t.frame.width}px`], ['frame-height', `${t.frame.height}px`], ['frame-min-width', `${t.frame.minWidth}px`], ['frame-max-width', `${t.frame.maxWidth}px`]]);

  const header = [
    '/* GENERATED by tools/design/tokens-to-css.mjs — не править руками.',
    ` * Источник: src/design/tokens.json (version ${t.version}) и src/design/motion.json (version ${m.version}).`,
    ' * Те же имена — в tokens.uss Unity-порта. Новое значение сначала добавьте в JSON. */',
  ];
  return `${header.join('\n')}\n\n:root {\n${groups.join('\n\n')}\n}\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const css = buildCss();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== css) {
      console.error('src/design/tokens.css устарел: запустите npm run tokens');
      process.exit(1);
    }
    console.log('src/design/tokens.css совпадает с tokens.json и motion.json');
  } else {
    fs.writeFileSync(outPath, css);
    console.log(`записан ${path.relative(root, outPath)} (${css.split('\n').filter(l => l.trim().startsWith('--')).length} переменных)`);
  }
}
